#!/usr/bin/env python3
"""Genera THIRD-PARTY-LICENSES.md con las licencias de las dependencias de compilación.

Recorre el grafo normal (sin dev-dependencies ni el propio morph) con `cargo metadata`
y agrupa los textos de licencia idénticos. Solo usa la biblioteca estándar.
Uso: scripts/third-party-licenses.py [salida]   (por defecto THIRD-PARTY-LICENSES.md)
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "THIRD-PARTY-LICENSES.md"
LICENSE_RE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.IGNORECASE)


def host_triple():
    out = subprocess.run(["rustc", "-vV"], capture_output=True, text=True, check=True).stdout
    return re.search(r"^host: (\S+)", out, re.M).group(1)


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", host_triple()],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)


def build_graph_ids(meta):
    """Ids alcanzables desde morph por dependencias normales o de build."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        cur = stack.pop()
        for dep in nodes[cur]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if not kinds & {None, "build"}:
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    seen.discard(root)
    return seen


def license_files(d):
    return sorted(
        f for f in d.iterdir() if f.is_file() and LICENSE_RE.match(f.name)
    ) if d.is_dir() else []


def find_license_files(manifest):
    d = manifest.parent
    files = license_files(d)
    if files:
        return files
    # Paquete de un repo git sin archivo propio: subir hasta la raíz del checkout.
    for parent in d.parents:
        if (parent / ".git").exists() or (parent / "Cargo.lock").exists() \
                or parent.name.startswith("checkouts") or parent.parent.name == "checkouts":
            files = license_files(parent)
            if files:
                return files
            if (parent / ".git").exists() or parent.parent.name == "checkouts":
                break
    return []


def main():
    meta = metadata()
    ids = build_graph_ids(meta)
    pkgs = sorted(
        (p for p in meta["packages"] if p["id"] in ids),
        key=lambda p: (p["name"], p["version"]),
    )
    texts = {}  # texto -> índice
    order = []
    entries = []
    for p in pkgs:
        refs = []
        for f in find_license_files(Path(p["manifest_path"])):
            t = f.read_text(errors="replace").strip()
            if t not in texts:
                texts[t] = len(order) + 1
                order.append(t)
            refs.append((f.name, texts[t]))
        entries.append((p, refs))

    lines = [
        "# Third-party licenses",
        "",
        "Morph is licensed under GPL-3.0-only. It is built with the following third-party",
        "packages (normal build graph, no dev-dependencies). Generated by",
        "`scripts/third-party-licenses.py` (`just licenses`); do not edit by hand.",
        "",
        f"{len(entries)} packages.",
        "",
        "## Packages",
        "",
    ]
    for p, refs in entries:
        lines.append(f"### {p['name']} {p['version']}")
        lines.append("")
        lines.append(f"- License: {p['license'] or p['license_file'] or 'unspecified'}")
        if p.get("repository"):
            lines.append(f"- Repository: {p['repository']}")
        if refs:
            lines.append("- License texts: " + ", ".join(
                f"{n} (see [text {i}](#license-text-{i}))" for n, i in refs))
        else:
            lines.append("- License texts: none found in the package")
        lines.append("")
    lines += ["## License texts", ""]
    for i, t in enumerate(order, 1):
        lines += [f'<a id="license-text-{i}"></a>', f"### License text {i}", "", "```text", t, "```", ""]
    OUT.write_text("\n".join(lines))
    missing = [p["name"] for p, r in entries if not r]
    print(f"{OUT}: {len(entries)} paquetes, {len(order)} textos distintos, "
          f"{len(missing)} sin archivo de licencia", file=sys.stderr)
    if missing:
        print("  sin texto: " + ", ".join(missing), file=sys.stderr)


main()
